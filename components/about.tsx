// -----------------------------------------------------------------------------
// IMPORTS
// ----------------------------------------------------------------------------

// Τα Chakra components που χρησιμοποιούμε για το About section.
//
// Box
// → δημιουργεί το εξωτερικό section.
//
// Container
// → κρατά το περιεχόμενο στο ίδιο μέγιστο πλάτος
//   με το Navbar και το Hero.
//
// Heading
// → χρησιμοποιείται για τον τίτλο της ενότητας.
//
// Stack
// → οργανώνει κάθετα τα στοιχεία και ελέγχει
//   το κενό ανάμεσά τους.
//
// Text
// → χρησιμοποιείται για τις παραγράφους.
import {
  Box,
  Container,
  Heading,
  Stack,
  Text,
} from "@chakra-ui/react";

// -----------------------------------------------------------------------------
// ABOUT COMPONENT
// -----------------------------------------------------------------------------

// Το About δίνει μια σύντομη εικόνα για το ποιος είμαι.
//
// Δεν γράφουμε εδώ ολόκληρη την προσωπική ιστορία.
// Η αρχική σελίδα πρέπει να παραμένει εύκολη στην ανάγνωση.
//
// Αργότερα θα δημιουργήσουμε ξεχωριστό route:
//
// /about
//
// Εκεί θα υπάρχει η αναλυτικότερη εκδοχή της ιστορίας μου.
export function About() {
  return (
    // Το semantic <section> δηλώνει ότι αυτό είναι
    // μια ξεχωριστή θεματική ενότητα της σελίδας.
    <Box
      as="section"
      py={{ base: 12, md: 16 }}
    >
      <Container maxW="3xl">
        <Stack
          gap={5}
          align="flex-start"
        >
          {/* Ο βασικός τίτλος της ενότητας. */}
          <Heading
            as="h2"
            fontSize={{ base: "2xl", md: "3xl" }}
            letterSpacing="tight"
          >
            Σχετικά με εμένα
          </Heading>

          {/*
           * Αναφέρουμε ανοιχτά τον αυτισμό και τη ΔΕΠΥ,
           * επειδή αποτελούν μέρος της πραγματικής
           * εκπαιδευτικής και προσωπικής μου διαδρομής.
           */}
          <Text
            color="fg.muted"
            lineHeight="tall"
            maxW="2xl"
          >
            Είμαι ο Αλέξανδρος, 28 ετών με αυτισμό και ΔΕΠΥ.
            Η εκπαιδευτική μου πορεία δεν ήταν γραμμική και 
            για αρκετά χρόνια η εμπειρία μου μέσα στην εκπαίδευση 
            με έκανε να αμφιβάλλω για την ικανότητα μου να μαθαίνω.
          </Text>
          
          {/*
           * Η δεύτερη παράγραφος μεταφέρει την ιστορία
           * από το παρελθόν στο σήμερα.
           *
           * Δεν παρουσιάζουμε τα projects απλώς ως προϊόντα.
           * Τα παρουσιάζουμε ως μέρος του τρόπου με τον οποίο
           * επέστρεψα ενεργά στη μάθηση.
           
          */}
          <Text
            color="fg.muted"
            lineHeight="tall"
            maxW="2xl"
          > 
            Σήμερα χρησιμοποιώ την περιέργεια και τα προσωπικά μου 
            projects για να χτίσω ξανά τη σχέση μου με τη μάθηση.
            Όταν κάτι μου δημιουργεί μια ερώτηση, προσπαθώ να μην 
            σταματάω μόνο στην απάντηση: θέλω να καταλάβω αν μπορώ 
            να το μελετήσω, να το κατασκευάσω και τελικά να εξηγήσω 
            πώς λειτουργεί.
          </Text>

          {/*
           * Η τελευταία παράγραφος συνδέει το προσωπικό
           * κομμάτι με την τεχνική μου κατεύθυνση.
          */}
          <Text
            color="fg.muted"
            lineHeight="tall"
            maxW="2xl"
          >
            Έχω ολοκληρώσει την εκπαίδευση μου ως Τεχνικών Δικτύων 
            και Τηλεπικοινωνιών. Έχω παρακολουθήσει διάφορα CISCO Courses. Με ενδιαφέρουν κυρίως τα Δίκτυα και την Ασφάλεια.
            
          </Text>
        </Stack>
      </Container>
    </Box>
  );
}
