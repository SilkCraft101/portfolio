// -----------------------------------------------------------------------------
// IMPORTS
// -----------------------------------------------------------------------------

// Τα Chakra components που χρειαζόμαστε για το πρώτο section
// της αρχικής σελίδας.
//
// Box
// → γενικό container για ομαδοποίηση περιεχομένου.
//
// Container
// → κρατά το Hero στο ίδιο μέγιστο πλάτος με το Navbar.
//
// Heading
// → semantic heading component για τον κύριο τίτλο.
//
// Stack
// → τοποθετεί τα children με ελεγχόμενο κενό μεταξύ τους.
//
// Text
// → χρησιμοποιείται για το εισαγωγικό και περιγραφικό κείμενο.
import {
  Box,
  Container,
  Heading,
  Stack,
  Text,
} from "@chakra-ui/react";

// -----------------------------------------------------------------------------
// HERO COMPONENT
// -----------------------------------------------------------------------------

// Το Hero είναι το πρώτο βασικό section που βλέπει ο επισκέπτης.
//
// Σκοπός του είναι να απαντά γρήγορα σε τρεις ερωτήσεις:
//
// 1. Ποιος είμαι;
// 2. Τι κάνω;
// 3. Τι είδους δουλειά / projects θα βρει κάποιος εδώ;
//
// Δεν βάζουμε ακόμη πολλά animations ή διακοσμητικά στοιχεία.
// Πρώτα δημιουργούμε σωστή δομή και visual hierarchy.
export function Hero() {
  return (
    // Το Box λειτουργεί ως semantic <section>.
    //
    // Με as="section" δημιουργούμε πραγματικό HTML <section>
// αντί για ένα γενικό <div>.
    <Box
      as="section"
      pt={{ base: 16, md: 24 }}
      pb={{ base: 12, md: 16 }}
    >
      {/*
        Χρησιμοποιούμε το ίδιο maxW με το Navbar.

        Έτσι οι αριστερές και δεξιές άκρες του Hero
        ευθυγραμμίζονται οπτικά με το navigation.
      */}
      <Container maxW="3xl">
        {/*
          Το Stack τοποθετεί τα στοιχεία κατακόρυφα.

          gap={5}
          → δημιουργεί σταθερό κενό μεταξύ των children.

          align="flex-start"
          → κρατά όλο το περιεχόμενο ευθυγραμμισμένο αριστερά.
        */}
        <Stack
          gap={5}
          align="flex-start"
        >
          {/* ---------------------------------------------------------------- */}
          {/* INTRODUCTION                                                     */}
          {/* ---------------------------------------------------------------- */}

          {/*
            Μικρό εισαγωγικό κείμενο πριν από τον κύριο τίτλο.

            Το muted semantic color το κάνει λιγότερο έντονο
            από το Heading και δημιουργεί visual hierarchy.
          */}
          <Text
            fontSize="sm"
            fontWeight="medium"
            color="fg.muted"
            letterSpacing="wide"
          >
            ΧΑΙΡΕΤΑΙ, ΜΕ ΛΕΝΕ ΑΛΕΞΑΝΔΡΟ
          </Text>

          {/* ---------------------------------------------------------------- */}
          {/* MAIN HEADING                                                     */}
          {/* ---------------------------------------------------------------- */}

          {/*
            Αυτό είναι το βασικό μήνυμα της αρχικής σελίδας.

            Το Heading αποδίδεται ως <h1>, επειδή πρόκειται
            για τον σημαντικότερο τίτλο της συγκεκριμένης σελίδας.

            Τα responsive font sizes σημαίνουν:

            base
            → μικρότερες οθόνες.

            md
            → medium οθόνες και πάνω.
          */}
          <Heading
            as="h1"
            fontSize={{
              base: "4xl",
              md: "6xl",
            }}
            lineHeight="1.05"
            letterSpacing="tight"
            maxW="2xl"
          >
            Μαθαίνω ανακαλύπτωντας απαντήσεις στα ερωτήματα μου.
          </Heading>

          {/* ---------------------------------------------------------------- */}
          {/* DESCRIPTION                                                      */}
          {/* ---------------------------------------------------------------- */}

          {/*
            Εδώ εξηγούμε λίγο περισσότερο το περιεχόμενο
            του portfolio.

            Το κείμενο είναι σκόπιμα μικρό και προσωρινό.
            Θα το προσαρμόσουμε ώστε να εκφράζει ακριβώς εσένα
            όταν ολοκληρώσουμε τη βασική εμφάνιση.

            maxW περιορίζει το μήκος κάθε γραμμής.
            Αυτό βελτιώνει την αναγνωσιμότητα σε μεγάλες οθόνες.
          */}
          <Text
            fontSize={{
              base: "md",
              md: "lg",
            }}
            color="fg.muted"
            lineHeight="tall"
            maxW="xl"
          >
            Έχω υπόβαθρο στα Δίκτυα και τις Τηλεπικοινωνίες και κύριο 
            ενδιαφέρον τα δίκτυα, την ασφάλεια και την κατανόηση του τρόπου με 
            τον οποίο λειτουργούν τα συστήματα.
          </Text>
        </Stack>
      </Container>
    </Box>
  );
}
