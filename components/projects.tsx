// -----------------------------------------------------------------------------
// IMPORTS
// -----------------------------------------------------------------------------

// Τα Chakra components που χρησιμοποιούμε για την ενότητα των Projects.
//
// Box
// → δημιουργεί το εξωτερικό section.
//
// Container
// → κρατά το περιεχόμενο ευθυγραμμισμένο με τα υπόλοιπα
//   sections της αρχικής σελίδας.
//
// Heading
// → χρησιμοποιείται για τον τίτλο της ενότητας.
//
// Stack
// → οργανώνει κάθετα το περιεχόμενο.
//
// Text
// → χρησιμοποιείται για το εισαγωγικό κείμενο.
import {
  Box,
  Container,
  Heading,
  Stack,
  Text,
} from "@chakra-ui/react";

// -----------------------------------------------------------------------------
// PROJECTS COMPONENT
// -----------------------------------------------------------------------------

// Το Projects θα παρουσιάζει τα τεχνικά projects που δημιουργώ
// καθώς μαθαίνω.
//
// Δεν παρουσιάζουμε τα projects σαν ολοκληρωμένα προϊόντα.
//
// Θέλουμε να φαίνεται:
// - γιατί ξεκίνησε κάθε project,
// - σε ποιο στάδιο βρίσκεται,
// - τι έχω ήδη δημιουργήσει,
// - τι έχω μάθει,
// - και ποιο είναι το επόμενο τεχνικό βήμα.
//
// Οι φωτογραφίες, η ζωγραφική και η μουσική δεν ανήκουν εδώ.
// Θα αποκτήσουν αργότερα ξεχωριστή δημιουργική ενότητα.
export function Projects() {
  return (
    // Κάθε βασικό κομμάτι της Home Page είναι
    // ξεχωριστό semantic section.
    <Box
      as="section"
      py={{ base: 12, md: 16 }}
    >
      <Container maxW="3xl">
        <Stack
          gap={5}
          align="flex-start"
        >
          {/* Ο τίτλος της ενότητας. */}
          <Heading
            as="h2"
            fontSize={{ base: "2xl", md: "3xl" }}
            letterSpacing="tight"
          >
            Projects
          </Heading>

          {/*
           * Εξηγώ τι σημαίνουν τα projects για εμένα,
           * αντί να εμφανίζω απλώς μια λίστα τεχνολογιών.
           */}
          <Text
            color="fg.muted"
            lineHeight="tall"
            maxW="2xl"
          >
            Τα projects μου ξεκινούν συνήθως από μια, κατά πάσα
            πιθανότητα, υπαρξιακή ερώτηση, μια ανάγκη ή κάτι που
            θέλω να καταλάβω καλύτερα. Τα χρησιμοποιώ ως χώρο
            μελέτης, πειραματισμού και εφαρμογής όσων μαθαίνω
            στην πράξη. Κάθε project που ξεκινώ είναι η αρχή
            αναζήτησης ενός «γιατί;».
          </Text>

          {/*
           * Είναι σημαντικό να είμαι ξεκάθαρος ότι τα projects μου
           * εξελίσσονται μαζί με τις γνώσεις μου.
           */}
          <Text
            color="fg.muted"
            lineHeight="tall"
            maxW="2xl"
          >
            Κανένα από αυτά δεν παρουσιάζεται ως «τελειωμένο».
            Καταγράφω την πραγματική του κατάσταση, όσα έχω ήδη
            κατασκευάσει, όσα έχω μάθει και το επόμενο βήμα που
            προσπαθώ να κατανοήσω.
          </Text>
        </Stack>
      </Container>
    </Box>
  );
}
